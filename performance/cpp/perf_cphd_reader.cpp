// Performance characterization for CPHDReaderOp — the SAR ingress, and the
// one operator in the chain whose hot path is host work rather than kernels:
// a file read, a byte-order swap and format decode, and a host-to-device
// upload, once per tick. Sweeps the batch size (pulses_per_tick) and the
// stored sample format, since those are what move the per-tick cost.
//
// Two things make this tool read differently from the others. The subject is
// a source, so there is no upstream operator to timestamp from and the reader
// is subclassed to stamp its own tick. And it is bounded: a reader stops when
// its collection is exhausted, so the achievable frame count is a property of
// the file rather than of --frames, and a scenario reports how many frames it
// actually got.
//
// By default it reads the generated mode01 fixtures out of the test tree. Set
// HOLOSCAN_RADAR_PERF_CPHD to characterize against a real collection instead,
// which is the measurement that matters for I/O — the fixtures are megabytes
// and sit in page cache. An environment variable rather than a flag because
// the shared driver's CLI is deliberately common to every consumer.
//
// Measurement tool only: no timing assertions. See
// docs/planning/OPERATOR_DEVELOPMENT.md.

