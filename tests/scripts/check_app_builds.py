"""Exercise the application manifests through the installed CLI in the GPU SDK container."""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import deque
from pathlib import Path


def invoke(args, label, command, *, env=None):
    print(f"{label}: {command[0]}", flush=True)
    log = args.log_dir / f"{args.case}-{label}.log"
    with log.open("w") as output:
        result = subprocess.run(
            command, cwd=args.source, env=env, stdout=output, stderr=subprocess.STDOUT, check=False
        )
    if result.returncode:
        with log.open(errors="replace") as output:
            sys.stderr.writelines(deque(output, maxlen=80))
        raise RuntimeError(f"{label} exited with {result.returncode}. Log: {log}")
    return log


def cli(args, label, parent, *command, language):
    env = os.environ.copy()
    env["HOLOSCAN_CLI_BUILD_PARENT_DIR"] = str(parent)
    # Use the SDK and provider resolved by the CLI rather than a caller's build tree.
    env.pop("PYTHONPATH", None)
    env.setdefault("CMAKE_CXX_COMPILER_LAUNCHER", "ccache")
    env.setdefault("CMAKE_CUDA_COMPILER_LAUNCHER", "ccache")
    return invoke(
        args,
        label,
        [
            sys.executable,
            "-m",
            "holoscan_cli",
            "--project-root",
            str(args.source),
            *command,
            "--language",
            language,
            "--local",
            "--local-sdk-root=/usr",
            "--build-type=rel-debug",
            "--parallel=4",
        ],
        env=env,
    )


def default_build(args, label, directory):
    cache = (directory / "CMakeCache.txt").read_text()
    for option in ("BUILD_ALL", "HOLOSCAN_RADAR_BUILD_TESTING", "PKG_holoscan_radar"):
        if not re.search(rf"^{option}:[^=]+=OFF$", cache, re.MULTILINE):
            raise RuntimeError(f"{label}: expected {option}=OFF in the application build")
    log = invoke(args, f"{label}-ninja", ["ninja", "-C", str(directory), "-t", "commands", "all"])
    return log.read_text()


def require_target(commands, target, label, *, present=True):
    # Inspect the object paths generated by Ninja for the default target's closure.
    if (f"CMakeFiles/{target}.dir/" in commands) != present:
        expected = "include" if present else "omit"
        raise RuntimeError(f"{label}: expected the default build to {expected} {target}")


def check_matrix(args, work):
    applications = {}
    for path in sorted(args.source.glob("applications/*/*/python/metadata.json")):
        name = json.loads(path.read_text())["application"]["name"]
        if name in applications:
            raise RuntimeError(f"Duplicate Python application manifest: {name}")
        applications[name] = path.relative_to(args.source).parts[1]
    if not applications:
        raise RuntimeError("No Python application manifests were found")

    for name, family in applications.items():
        parent = work / "python"
        cli(args, name, parent, "build", name, "--target=help", language="python")
        commands = default_build(args, name, parent / name)
        require_target(commands, "holoscan_radar_python", name)
        if family == "fmcw":
            require_target(commands, name, name, present=False)

    parent = work / "multiple"
    cli(
        args,
        "multiple",
        parent,
        "build",
        "siso",
        "smoke",
        "--target=help",
        "--configure-args=-DAPP_simo=ON",
        "--configure-args=-DOP_music_estimator_op=ON",
        "--configure-args=-DHOLOSCAN_RADAR_APPLICATION=siso",
        language="cpp",
    )
    commands = default_build(args, "multiple", parent / "siso")
    for target in ("siso", "simo", "music_estimator_op"):
        require_target(commands, target, "multiple")
    print(f"Configured {len(applications)} Python applications and a multiple-component C++ build")


def check_siso(args, work):
    for index, language in enumerate(("cpp", "python", "cpp"), start=1):
        label = f"{index}-{language}"
        log = cli(args, label, work, "run", "siso", "smoke", language=language)
        reports = re.findall(
            r"centroid range [0-9.]+ m, velocity -?[0-9.]+ m/s", log.read_text(errors="replace")
        )
        if len(reports) != 2:
            raise RuntimeError(f"{label}: expected two SISO detection reports, got {len(reports)}")
        commands = default_build(args, label, work / "siso")
        require_target(commands, "siso", label, present=language == "cpp")
        require_target(commands, "holoscan_radar_python", label, present=language == "python")
        print(f"{label}: received both SISO detection reports", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("case", choices=("ApplicationConfigureMatrix", "ApplicationCliSisoSmoke"))
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--work", required=True, type=Path)
    parser.add_argument("--log-dir", required=True, type=Path)
    args = parser.parse_args()
    args.source = args.source.resolve()
    args.log_dir = args.log_dir.resolve()
    args.log_dir.mkdir(parents=True, exist_ok=True)
    args.work.mkdir(parents=True, exist_ok=True)
    # Leave generated graphs in the dashboard tree for diagnosis until the next dashboard run.
    work = Path(tempfile.mkdtemp(prefix=f"{args.case}-", dir=args.work.resolve()))
    if args.case == "ApplicationConfigureMatrix":
        check_matrix(args, work)
    else:
        check_siso(args, work)


if __name__ == "__main__":
    main()
